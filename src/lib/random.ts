// Willekeur die je kunt herhalen: zelfde seed = zelfde uitkomst (bingokaart, liftvraag van de dag).

/** Klein, voorspelbaar random-getal uit een tekst. */
export function seeded(seed: string): () => number {
  let h = 2166136261
  for (let i = 0; i < seed.length; i++) h = Math.imul(h ^ seed.charCodeAt(i), 16777619)
  let a = h >>> 0
  return () => {
    a = (a + 0x6d2b79f5) >>> 0
    let t = a
    t = Math.imul(t ^ (t >>> 15), t | 1)
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61)
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296
  }
}

/** Eerlijk schudden (Fisher-Yates). */
export function shuffle<T>(xs: readonly T[], rng: () => number = Math.random): T[] {
  const a = [...xs]
  for (let i = a.length - 1; i > 0; i--) {
    const j = Math.floor(rng() * (i + 1))
    ;[a[i], a[j]] = [a[j], a[i]]
  }
  return a
}

export const pick = <T>(xs: readonly T[], n: number, rng: () => number = Math.random) => shuffle(xs, rng).slice(0, n)
